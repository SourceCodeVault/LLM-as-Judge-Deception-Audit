def main():
    target = select_run()
    if not target:
        return

    print(f"\n📂 Parsing pipeline data within: {target.name}")
    
    # Run Guardrails to verify target context structure
    config_path = target / "_provenance" / "config.json"
    if config_path.exists():
        with open(config_path, "r") as f:
            config = json.load(f)
            if config.get("run_type") == "test_retest":
                print("❌ ERROR: Targeted a Test-Retest run directory. Aborting.")
                return

    signals, correlated, total_scanned = process_gaps(target)
    gen_time = datetime.now().strftime("%d %B %Y · %H:%M")

    # Serialize programmatic payload to JSON disk
    json_payload = {
        "run_directory": target.name,
        "scanned_at": gen_time,
        "total_files_scanned": total_scanned,
        "metrics": {
            "total_signals_triaged": len(signals),
            "cross_variant_gaps_count": len(correlated),
            "schema_coherence_crashes": sum(1 for s in signals if s["schema_crash"]),
            "auditor_breaks_count": sum(1 for s in signals if s["auditor_break"])
        },
        "granular_signals": signals,
        "cross_variant_correlations": correlated
    }
    
    out_json = target / "policy_gap_report.json"
    out_json.write_text(json.dumps(json_payload, indent=2), encoding="utf-8")
    print(f"✅ Machine-readable payload written: {out_json.name}")

    # Render print-ready HTML diagnostic layout
    html_layout = render_html_report(target, signals, correlated, total_scanned, gen_time)
    out_html = target / "policy_gap_report.html"
    out_html.write_text(html_layout, encoding="utf-8")
    print(f"✅ Diagnostic dashboard layout written: {out_html.name}")

    try:
        webbrowser.open(f"file://{out_html.resolve()}")
    except Exception:
        pass

if __name__ == "__main__":
    main()